package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"slices"
)

// agentToolCatalog is the spec's top-level x-agent-tools.
type agentToolCatalog struct {
	Tags   []string `json:"tags"`
	Groups []struct {
		Tag         string `json:"tag"`
		Name        string `json:"name"`
		Description string `json:"description"`
	} `json:"groups"`
	Tools []struct {
		Name              string   `json:"name"`
		Description       string   `json:"description"`
		RequiresWorkspace bool     `json:"requiresWorkspace"`
		Tags              []string `json:"tags"`
	} `json:"tools"`
}

// parseCatalog reads x-agent-tools, failing on a key the generator would drop.
func parseCatalog(raw json.RawMessage) (*agentToolCatalog, error) {
	if raw == nil {
		return nil, fmt.Errorf("%s has no x-agent-tools", specPath)
	}
	dec := json.NewDecoder(bytes.NewReader(raw))
	dec.DisallowUnknownFields()
	var c agentToolCatalog
	if err := dec.Decode(&c); err != nil {
		return nil, fmt.Errorf("x-agent-tools: %w", err)
	}
	return &c, nil
}

// renderCatalog renders agenttools.go, recording each constant in consts. Each tool's first
// tag is its group, and an optional second tag, one outside every group, is its file access.
func (g *gen) renderCatalog(c *agentToolCatalog, consts map[string]string) ([]byte, error) {
	var groupTags, accessTags []string
	for _, gr := range c.Groups {
		if !slices.Contains(c.Tags, gr.Tag) || slices.Contains(groupTags, gr.Tag) {
			return nil, fmt.Errorf("x-agent-tools: group tag %q is undeclared or repeated", gr.Tag)
		}
		groupTags = append(groupTags, gr.Tag)
	}
	for _, t := range c.Tags {
		if !slices.Contains(groupTags, t) {
			accessTags = append(accessTags, t)
		}
	}
	var b bytes.Buffer
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	w("// Code generated by specgen from spec/openapi.json. DO NOT EDIT.\n\npackage blazingagents\n\n")
	tagConsts := map[string]string{}
	writeTags := func(typ, doc string, values []string) error {
		w("%s\ntype %s string\n\n// %s values.\nconst (\n", doc, typ, typ)
		for _, v := range values {
			name, err := constName(consts, typ, v)
			if err != nil {
				return err
			}
			tagConsts[v] = name
			w("\t%s %s = %q\n", name, typ, v)
		}
		w(")\n\n")
		return nil
	}
	if err := writeTags("AgentToolGroupTag", "// AgentToolGroupTag names a group of built-in tools. Every tool in AgentTools has one.", groupTags); err != nil {
		return nil, err
	}
	if err := writeTags("AgentToolFileAccessTag", `// AgentToolFileAccessTag is what a built-in tool can do to Workspace files. A "file_read"
// tool never changes them, so an Agent whose file tools are all "file_read" is read-only.
// An "execute" tool runs arbitrary commands, which can change files and more.`, accessTags); err != nil {
		return nil, err
	}
	w("%s\n\n", catalogDecl)
	w("// AgentToolGroups is the groups of AgentTools, in display order.\nvar AgentToolGroups = []AgentToolGroup{\n")
	for _, gr := range c.Groups {
		w("\t{Tag: %s, Name: %q, Description: %q},\n", tagConsts[gr.Tag], gr.Name, gr.Description)
	}
	w("}\n\n")
	w("// AgentTools is every built-in tool an Agent can enable through Tools, in display order.\nvar AgentTools = []AgentToolDefinition{\n")
	var names []string
	for _, t := range c.Tools {
		if !g.enums["AgentTool"][t.Name] || slices.Contains(names, t.Name) {
			return nil, fmt.Errorf("x-agent-tools: tool %q is not an AgentTool value, or is repeated", t.Name)
		}
		names = append(names, t.Name)
		if len(t.Tags) == 0 || len(t.Tags) > 2 || !slices.Contains(groupTags, t.Tags[0]) || len(t.Tags) == 2 && !slices.Contains(accessTags, t.Tags[1]) {
			return nil, fmt.Errorf("x-agent-tools: tool %q has tags %v; want a group tag and at most one other declared tag", t.Name, t.Tags)
		}
		w("\t{Name: AgentTool%s, Description: %q, RequiresWorkspace: %t, Group: %s", valueName("AgentTool", t.Name), t.Description, t.RequiresWorkspace, tagConsts[t.Tags[0]])
		if len(t.Tags) == 2 {
			w(", FileAccess: %s", tagConsts[t.Tags[1]])
		}
		w("},\n")
	}
	w("}\n")
	return format.Source(b.Bytes())
}

const catalogDecl = `// AgentToolGroup is a group of built-in tools, as display code shows it.
type AgentToolGroup struct {
	Tag         AgentToolGroupTag
	Name        string
	Description string
}

// AgentToolDefinition is a built-in tool an Agent can enable through Tools. Its tags describe
// it and never enable it.
type AgentToolDefinition struct {
	Name              AgentTool
	Description       string
	RequiresWorkspace bool // the tool runs in the Agent's attached Workspace
	Group             AgentToolGroupTag
	FileAccess        AgentToolFileAccessTag // "" when the tool declares none
}`
